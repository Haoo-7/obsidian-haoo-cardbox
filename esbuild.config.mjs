// esbuild 构建脚本：打包 src/main.ts 到 dist/main.js，并把 manifest.json / styles.css /
// versions.json 复制到 dist/，使 dist 目录可直接作为插件安装到 vault 中。
import esbuild from "esbuild";
import process from "process";
import { copyFileSync, mkdirSync } from "node:fs";

const prod = process.argv[2] === "production";

// 确保 dist 目录存在
mkdirSync("dist", { recursive: true });

const banner =
	`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const buildOptions = {
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "dist/main.js",
	minify: prod,
	platform: "node",
};

// 需要随构建产物一起发布的静态文件
const assets = ["manifest.json", "styles.css", "versions.json"];
function copyAssets() {
	for (const file of assets) {
		copyFileSync(file, `dist/${file}`);
	}
}

if (prod) {
	await esbuild.build(buildOptions);
	copyAssets();
	console.log("生产构建完成，产物在 dist/。");
} else {
	const ctx = await esbuild.context(buildOptions);
	await ctx.watch();
	copyAssets();
	console.log("监听模式：正在监视源文件变化……");
}
